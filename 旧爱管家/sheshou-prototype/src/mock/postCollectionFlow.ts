/**
 * 回收后完整业务流程
 *
 * ┌─────────────────────────────────────────────────────────────┐
 * │ 第一阶段：确认回收清单 → 生成订单 (步骤12)                      │
 * ├─────────────────────────────────────────────────────────────┤
 * │ 根据鉴定结果 + 客户选择，拆分为：                               │
 * │   • 全额竞价回收订单（鉴定真 + 客户当场卖）                      │
 * │   • 定金竞价回收订单（需总部复检 + 客户当场卖）                   │
 * │   • 寄卖竞价回收订单（客户选择寄卖）                             │
 * │ 一种回收类型 = 一个订单 = 一份合同                               │
 * └─────────────────────────────────────────────────────────────┘
 *
 * ┌─────────────────────────────────────────────────────────────┐
 * │ 第二阶段：合同签署 + 打款 (步骤13)                              │
 * ├─────────────────────────────────────────────────────────────┤
 * │ 1. 系统生成合同（按订单类型分别生成）                            │
 * │ 2. 客户线上逐份签署合同                                        │
 * │ 3. 鉴定师发起打款申请                                          │
 * │ 4. 打款审批流程（按金额分级）：                                  │
 * │    • ≤2万：鉴定师申请 → 大区经理审批                            │
 * │    • 2-5万：+ 大区总监审批                                     │
 * │    • 5-10万：+ 总经理审批                                      │
 * │    • >10万：+ 财务审批                                         │
 * │ 5. 审批通过 → 打款                                             │
 * └─────────────────────────────────────────────────────────────┘
 *
 * ┌─────────────────────────────────────────────────────────────┐
 * │ 第三阶段：门店 → 总部 (步骤14前半)                              │
 * ├─────────────────────────────────────────────────────────────┤
 * │ 鉴定师操作：                                                   │
 * │ 1. 待完善 → 确认配件和商品描述                                  │
 * │ 2. 待入库 → 点入库（入到门店本地仓）                             │
 * │ 3. 待调拨 → 选择商品 → 发快递到总部仓                           │
 * │                                                               │
 * │ 总部仓管操作：                                                  │
 * │ 4. 签收快递包裹                                                │
 * │ 5. 核验：商品与描述是否一致（配件/磨损/是否调包）                  │
 * │    • 一致 → 入库成功                                           │
 * │    • 不一致 → 异常处理，通知门店鉴定师                           │
 * └─────────────────────────────────────────────────────────────┘
 *
 * ┌─────────────────────────────────────────────────────────────┐
 * │ 第四阶段：总部复检 (步骤14后半)                                 │
 * ├─────────────────────────────────────────────────────────────┤
 * │ 1. 推送到复检部门                                              │
 * │ 2. 两个鉴定师并行复检                                          │
 * │    • 双真 → 正品                                               │
 * │    • 双假 → 假货                                               │
 * │    • 不一致 → 第三人复检                                        │
 * │      • 第三人确定 → 最终结论                                    │
 * │      • 第三人存疑 → 申请外部第三方鉴定（中检/中诉）               │
 * │ 3. 最终结论：真 → 收，假 → 退回客户                             │
 * │ 4. 出具鉴定报告                                                │
 * └─────────────────────────────────────────────────────────────┘
 *
 * ┌─────────────────────────────────────────────────────────────┐
 * │ 第五阶段：定价 → 拍照编辑 → 上架 (步骤15前半)                   │
 * ├─────────────────────────────────────────────────────────────┤
 * │ 1. 定价：设定多渠道价格                                        │
 * │    • 成本价（收购价）                                           │
 * │    • 同行价                                                    │
 * │    • 零售价                                                    │
 * │    • 直播价                                                    │
 * │    • 暗拍起拍价                                                │
 * │ 2. 专业棚拍 + 商品信息编辑                                      │
 * │ 3. 上架到销售仓                                                │
 * └─────────────────────────────────────────────────────────────┘
 *
 * ┌─────────────────────────────────────────────────────────────┐
 * │ 第六阶段：销售 → 结算 (步骤15后半)                              │
 * ├─────────────────────────────────────────────────────────────┤
 * │ 1. 渠道分发：抖音/小红书/得物/闲鱼/门店                         │
 * │ 2. 借出/归还（展会、三方鉴定等）                                │
 * │ 3. 仓间调拨（总仓→门店展厅等）                                  │
 * │ 4. 组货 → 开销售单                                             │
 * │ 5. 生成支付二维码 → 客户付款                                    │
 * │ 6. 付款成功 → 拣货单 → 出库单 → 发货                           │
 * │ 7. 客户签收（或发起售后）                                       │
 * │ 8. 财务对账 → 计算提成                                          │
 * │ 9. 寄卖订单：售出后7天打款（扣佣金）                             │
 * └─────────────────────────────────────────────────────────────┘
 */

